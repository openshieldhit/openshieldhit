/**
 * @brief Map public ICRU ids into the dense embedded table index space.
 */
static int icru_db_map_id(int icru_id) {
    if (icru_id == _GRAPHITE_ICRU_ID) {
        return _GRAPHITE_INTERNAL_ID;
    }
    return icru_id;
}

/**
 * @brief Return nonzero if ICRU classifies the material as gaseous.
 */
static int icru_db_is_gas(int icru_id) {
    size_t i;
    size_t n_gases;

    n_gases = sizeof(_icru_db_gases) / sizeof(_icru_db_gases[0]);
    i = 0;
    while (i < n_gases) {
        if (icru_id == _icru_db_gases[i]) {
            return 1;
        }
        i++;
    }
    return 0;
}

double osh_material_icru_compound_element_mean_excitation_energy(unsigned int z, int state, double pure_element_mee) {
    if (state == OSH_MATERIAL_STATE_GAS) {
        switch (z) {
        case 6u:
            return 70.0; /* carbon in gaseous compounds */
        case 7u:
            return 82.0; /* nitrogen in gaseous compounds */
        case 8u:
            return 97.0; /* oxygen in gaseous compounds */
        default:
            return pure_element_mee;
        }
    }

    if (state == OSH_MATERIAL_STATE_CONDENSED) {
        switch (z) {
        case 1u:
            return 19.2; /* hydrogen in condensed compounds */
        case 6u:
            return 85.9; /* carbon in condensed compounds */
        case 7u:
            return 81.0; /* nitrogen in condensed compounds */
        case 8u:
            return 106.0; /* oxygen in condensed compounds */
        case 9u:
            return 112.0; /* fluorine in condensed compounds */
        case 17u:
            return 180.0; /* chlorine in condensed compounds */
        default:
            return pure_element_mee;
        }
    }

    return pure_element_mee;
}

/**
 * @brief Copy an elemental ICRU entry into caller-owned storage.
 */
static enum osh_status
icru_db_fill_element_entry(int icru_id, int id, int midx, struct osh_material_icru_entry *entry_out) {
    entry_out->icru_id = icru_id;
    entry_out->rho = (double) _icru_db_densities[midx];
    entry_out->mean_excitation_energy = (double) _icru_db_mean_excitation_energies[midx];
    entry_out->state = icru_db_is_gas(icru_id) ? OSH_MATERIAL_STATE_GAS : OSH_MATERIAL_STATE_CONDENSED;
    entry_out->nelements = 1u;
    entry_out->elements[0].z = (unsigned int) id;
    entry_out->elements[0].a = 0u;
    entry_out->elements[0].mass_fraction = 1.0;

    return OSH_OK;
}

/**
 * @brief Copy a compound ICRU entry into caller-owned storage.
 */
static enum osh_status
icru_db_fill_compound_entry(int icru_id, int id, int midx, struct osh_material_icru_entry *entry_out) {
    int cidx;
    int start;
    size_t i;
    size_t nelements;

    cidx = id - _ICRU_DB_MINCOMPOUND_ID;
    nelements = (size_t) _icru_db_compound_element_counts[cidx];
    if (nelements > OSH_MATERIAL_ICRU_MAX_ELEMENTS) {
        return OSH_ESTATE;
    }

    entry_out->icru_id = icru_id;
    entry_out->rho = (double) _icru_db_densities[midx];
    entry_out->mean_excitation_energy = (double) _icru_db_mean_excitation_energies[midx];
    entry_out->state = icru_db_is_gas(icru_id) ? OSH_MATERIAL_STATE_GAS : OSH_MATERIAL_STATE_CONDENSED;
    entry_out->nelements = nelements;

    start = _icru_db_compound_index_offsets1[cidx] - 1;
    i = 0;
    while (i < nelements) {
        entry_out->elements[i].z = (unsigned int) _icru_db_compound_elements[start + (int) i];
        entry_out->elements[i].a = 0u;
        entry_out->elements[i].mass_fraction = (double) _icru_db_compound_fractions[start + (int) i];
        i++;
    }

    return OSH_OK;
}

enum osh_status osh_material_icru_lookup(int icru_id, struct osh_material_icru_entry *entry_out) {
    int id;
    int midx;

    if (!entry_out) {
        return OSH_EINVAL;
    }
    memset(entry_out, 0, sizeof(*entry_out));

    id = icru_db_map_id(icru_id);
    if (id <= 0 || id > _GRAPHITE_INTERNAL_ID) {
        return OSH_ENOTSUP;
    }

    midx = id - 1;
    if (id <= _ICRU_DB_MAXEL_ID) {
        return icru_db_fill_element_entry(icru_id, id, midx, entry_out);
    }
    if (id >= _ICRU_DB_MINCOMPOUND_ID) {
        return icru_db_fill_compound_entry(icru_id, id, midx, entry_out);
    }

    return OSH_ENOTSUP;
}
